const PROJECT_STATUSES = {
  DRAFT: 'DRAFT',
  SUBMITTED: 'SUBMITTED',
  UNDER_REVIEW: 'UNDER_REVIEW',
  AWAITING_INFORMATION: 'AWAITING_INFORMATION',
  ASSIGNED: 'ASSIGNED',
  IN_PROGRESS: 'IN_PROGRESS',
  INTERNAL_REVIEW: 'INTERNAL_REVIEW',
  CLIENT_REVIEW: 'CLIENT_REVIEW',
  REVISION_REQUESTED: 'REVISION_REQUESTED',
  APPROVED: 'APPROVED',
  COMPLETED: 'COMPLETED',
  CANCELLED: 'CANCELLED'
};

const ALL_STATUSES = Object.values(PROJECT_STATUSES);

// Centralized status transition map
const ALLOWED_TRANSITIONS = {
  [PROJECT_STATUSES.DRAFT]: [PROJECT_STATUSES.SUBMITTED, PROJECT_STATUSES.CANCELLED],
  [PROJECT_STATUSES.SUBMITTED]: [PROJECT_STATUSES.UNDER_REVIEW, PROJECT_STATUSES.AWAITING_INFORMATION, PROJECT_STATUSES.CANCELLED],
  [PROJECT_STATUSES.UNDER_REVIEW]: [PROJECT_STATUSES.AWAITING_INFORMATION, PROJECT_STATUSES.ASSIGNED, PROJECT_STATUSES.CANCELLED],
  [PROJECT_STATUSES.AWAITING_INFORMATION]: [PROJECT_STATUSES.SUBMITTED, PROJECT_STATUSES.UNDER_REVIEW, PROJECT_STATUSES.CANCELLED],
  [PROJECT_STATUSES.ASSIGNED]: [PROJECT_STATUSES.IN_PROGRESS, PROJECT_STATUSES.CANCELLED],
  [PROJECT_STATUSES.IN_PROGRESS]: [PROJECT_STATUSES.INTERNAL_REVIEW, PROJECT_STATUSES.CLIENT_REVIEW, PROJECT_STATUSES.CANCELLED],
  [PROJECT_STATUSES.INTERNAL_REVIEW]: [PROJECT_STATUSES.IN_PROGRESS, PROJECT_STATUSES.CLIENT_REVIEW, PROJECT_STATUSES.CANCELLED],
  [PROJECT_STATUSES.CLIENT_REVIEW]: [PROJECT_STATUSES.REVISION_REQUESTED, PROJECT_STATUSES.APPROVED, PROJECT_STATUSES.CANCELLED],
  [PROJECT_STATUSES.REVISION_REQUESTED]: [PROJECT_STATUSES.IN_PROGRESS, PROJECT_STATUSES.INTERNAL_REVIEW, PROJECT_STATUSES.CANCELLED],
  [PROJECT_STATUSES.APPROVED]: [PROJECT_STATUSES.COMPLETED, PROJECT_STATUSES.CANCELLED],
  [PROJECT_STATUSES.COMPLETED]: [],
  [PROJECT_STATUSES.CANCELLED]: []
};

const isValidTransition = (currentStatus, nextStatus) => {
  const allowed = ALLOWED_TRANSITIONS[currentStatus] || [];
  return allowed.includes(nextStatus);
};

module.exports = {
  PROJECT_STATUSES,
  ALL_STATUSES,
  ALLOWED_TRANSITIONS,
  isValidTransition
};
